package gen

import (
	"fmt"
	"strings"
	"text/template"

	"github.com/tamnd/tamago/pkg/spec"
)

// Standalone renders a single-file Go program that runs the agent against
// the Anthropic API: task in via argv or stdin, streamed answer out.
type Standalone struct{}

func (Standalone) Name() string { return "standalone" }

// mainTmpl uses << >> delimiters because the generated Go code itself
// contains {{ }} in composite literals.
var mainTmpl = template.Must(template.New("main").Delims("<<", ">>").Parse(`// <<.Header>>package main

import (
	"context"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/anthropics/anthropic-sdk-go"
)

const systemPrompt = <<.SystemPrompt>>

const model = "<<.Model>>"

func main() {
	task := strings.Join(os.Args[1:], " ")
	if strings.TrimSpace(task) == "" {
		b, err := io.ReadAll(os.Stdin)
		if err != nil {
			fmt.Fprintln(os.Stderr, "read stdin:", err)
			os.Exit(1)
		}
		task = string(b)
	}
	if strings.TrimSpace(task) == "" {
		fmt.Fprintln(os.Stderr, "usage: <<.Name>> \"task\" (or pipe the task on stdin)")
		os.Exit(2)
	}

	client := anthropic.NewClient()
	adaptive := anthropic.ThinkingConfigAdaptiveParam{}
	stream := client.Messages.NewStreaming(context.Background(), anthropic.MessageNewParams{
		Model:     model,
		MaxTokens: 16000,
		Thinking:  anthropic.ThinkingConfigParamUnion{OfAdaptive: &adaptive},
		System:    []anthropic.TextBlockParam{{Text: systemPrompt}},
		Messages: []anthropic.MessageParam{
			anthropic.NewUserMessage(anthropic.NewTextBlock(task)),
		},
	})
	for stream.Next() {
		event := stream.Current()
		if ev, ok := event.AsAny().(anthropic.ContentBlockDeltaEvent); ok {
			if d, ok := ev.Delta.AsAny().(anthropic.TextDelta); ok {
				fmt.Print(d.Text)
			}
		}
	}
	fmt.Println()
	if err := stream.Err(); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}
`))

var modTmpl = template.Must(template.New("mod").Parse(`module {{.Name}}-agent

go 1.26

require github.com/anthropics/anthropic-sdk-go v1.56.0
`))

var readmeTmpl = template.Must(template.New("readme").Parse(`# {{.Name}} (standalone agent)

{{.Job}}

Generated by tamago, generation {{.Gen}}. Risk class: {{.Risk}}.

Run it:

    export ANTHROPIC_API_KEY=...
    go mod tidy
    go run . "your task here"

Escalation: {{.Escalation}}
`))

func (Standalone) Generate(s *spec.AgentSpec) (map[string]string, error) {
	data := struct {
		Header, Name, Job, SystemPrompt, Model, Risk, Escalation string
		Gen                                                      int
	}{
		Header:       header(s, "//"),
		Name:         s.Name,
		Job:          s.Job,
		SystemPrompt: fmt.Sprintf("%q", strings.TrimSpace(s.SystemPrompt)),
		Model:        s.Model(),
		Risk:         s.Risk,
		Escalation:   s.Escalation,
		Gen:          s.Meta.Generation,
	}
	files := map[string]string{}
	for name, t := range map[string]*template.Template{
		"main.go":   mainTmpl,
		"go.mod":    modTmpl,
		"README.md": readmeTmpl,
	} {
		var b strings.Builder
		if err := t.Execute(&b, data); err != nil {
			return nil, err
		}
		files[name] = b.String()
	}
	return files, nil
}
