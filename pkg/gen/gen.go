// Package gen turns an AgentSpec into runnable artifacts. Generation is
// deterministic: no LLM calls, the same spec always produces the same files.
package gen

import (
	"fmt"

	"github.com/tamnd/tamago/pkg/spec"
)

// Target renders one artifact family from a spec.
type Target interface {
	Name() string
	// Generate returns relative file paths and their contents.
	Generate(s *spec.AgentSpec) (map[string]string, error)
}

// All returns every target in render order.
func All() []Target {
	return []Target{Claude{}, Standalone{}, Cron{}}
}

// ByName looks a target up.
func ByName(name string) (Target, error) {
	for _, t := range All() {
		if t.Name() == name {
			return t, nil
		}
	}
	return nil, fmt.Errorf("unknown target %q (have claude, standalone, cron)", name)
}

// header is stamped on generated files so their origin is obvious.
func header(s *spec.AgentSpec, comment string) string {
	return fmt.Sprintf("%s generated by tamago from %s (generation %d)\n%s do not edit by hand, edit the spec and regenerate\n",
		comment, s.Name, s.Meta.Generation, comment)
}
